import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../../domain/entities/inspection_report.dart';

class InspectionReportPdfService {
  const InspectionReportPdfService._();

  static Future<Uint8List> buildPdf(InspectionReport report) async {
    final document = pw.Document();

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(40),
        footer: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Divider(color: PdfColors.blueGrey300),
            pw.Text(
              'Generated by AutoDoc AI - Page ${context.pageNumber} of ${context.pagesCount}',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.blueGrey),
            ),
          ],
        ),
        build: (context) => [
          if (report.isSimulated) ...[
            pw.Container(
              width: double.infinity,
              padding: const pw.EdgeInsets.all(10),
              color: PdfColors.orange100,
              child: pw.Text(
                'SIMULATED DEMO REPORT - NOT A REAL INSPECTION',
                textAlign: pw.TextAlign.center,
                style: pw.TextStyle(
                  color: PdfColors.deepOrange900,
                  fontSize: 12,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ),
            pw.SizedBox(height: 12),
          ],
          if (!report.isSimulated && report.isPartial) ...[
            pw.Container(
              width: double.infinity,
              padding: const pw.EdgeInsets.all(10),
              color: PdfColors.orange100,
              child: pw.Text(
                'PARTIAL LIVE INSPECTION - UNAVAILABLE: '
                '${report.unavailableComponents.isEmpty ? 'some analysis components' : report.unavailableComponents.join(', ')}',
                textAlign: pw.TextAlign.center,
                style: pw.TextStyle(
                  color: PdfColors.deepOrange900,
                  fontSize: 11,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ),
            pw.SizedBox(height: 12),
          ],
          pw.Text(
            'AutoDoc AI',
            style: pw.TextStyle(
              color: PdfColor.fromHex('#071722'),
              fontSize: 24,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 4),
          pw.Text(
            'Vehicle inspection report',
            style: const pw.TextStyle(fontSize: 15, color: PdfColors.blueGrey),
          ),
          pw.SizedBox(height: 16),
          pw.Divider(color: PdfColors.blueGrey300),
          pw.SizedBox(height: 10),
          _pdfRow('Report ID', report.reportId),
          _pdfRow('Generated', report.generatedDate),
          _pdfRow('Vehicle', report.vehicleName),
          _pdfRow('Registration', report.registrationNumber),
          pw.SizedBox(height: 18),
          _sectionTitle('Inspection summary'),
          pw.SizedBox(height: 8),
          _pdfRow('Photos analyzed', '${report.photosAnalyzed}'),
          _pdfRow('Damage findings', report.damageSummary),
          _pdfRow('Engine audio label', report.audioLabel),
          _pdfRow('Base valuation estimate', report.baseEstimateLabel),
          _pdfRow('Reviewed repair allowance', report.repairAllowanceLabel),
          _pdfRow('Adjusted valuation estimate', report.adjustedEstimateLabel),
          if (!report.visualAnalysisAvailable)
            _pdfRow('Visual analysis', report.visualNotice),
          if (!report.audioAvailable)
            _pdfRow('Audio analysis', report.audioNotice),
          if (!report.valuationAvailable)
            _pdfRow('Valuation', report.valuationNotice),
          pw.SizedBox(height: 16),
          _sectionTitle('Visual findings'),
          pw.SizedBox(height: 8),
          if (report.findings.isEmpty)
            pw.Text('No visual findings returned by the inspection API.')
          else
            ...report.findings.indexed.map(
              (entry) => pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 8),
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      '${entry.$1 + 1}. ${entry.$2.label} - Photo ${entry.$2.imageIndex + 1} - ${entry.$2.confidenceLabel}',
                      style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                    ),
                    if (entry.$2.detail != null)
                      pw.Padding(
                        padding: const pw.EdgeInsets.only(top: 2),
                        child: pw.Text(
                          entry.$2.detail!,
                          style: const pw.TextStyle(fontSize: 9),
                        ),
                      ),
                  ],
                ),
              ),
            ),
          pw.SizedBox(height: 16),
          _sectionTitle('Automated summary'),
          pw.SizedBox(height: 6),
          pw.Text(report.voiceSummary),
          pw.SizedBox(height: 16),
          pw.Container(
            padding: const pw.EdgeInsets.all(12),
            decoration: pw.BoxDecoration(
              color: PdfColors.blueGrey50,
              borderRadius: pw.BorderRadius.circular(6),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                _sectionTitle('Important information'),
                pw.SizedBox(height: 6),
                pw.Text(
                  [
                    if (report.isSimulated) 'DEMO ONLY: all amounts and audio labels are randomly generated placeholders. No photos or audio were analyzed. Do not use this report for a purchase, repair or safety decision.',
                    if (!report.isSimulated && report.isPartial) 'PARTIAL LIVE REPORT: unavailable components were not analyzed and no substitute values were generated.',
                    if (report.visualAnalysisAvailable)
                      'Visual findings are experimental and may be inaccurate.',
                    if (report.audioAvailable) 'Audio classification is experimental and may be inaccurate.',
                    if (report.valuationAvailable) 'The valuation is a prototype estimate of historical listing asking price, not a formal appraisal or current-market valuation.',
                    'A reviewed repair allowance is caller-provided and is not inferred from the inspection. Findings require in-person verification. This report is not a mechanical safety certificate; no finding does not establish a damage-free or safe vehicle.',
                  ].join(' '),
                  style: const pw.TextStyle(
                    fontSize: 9,
                    lineSpacing: 3,
                    color: PdfColors.blueGrey800,
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );

    return document.save();
  }

  static Future<bool> sharePdf(InspectionReport report) async {
    final bytes = await buildPdf(report);
    final safeReportId = report.reportId.replaceAll(
      RegExp(r'[^A-Za-z0-9_-]'),
      '_',
    );

    return Printing.sharePdf(
      bytes: bytes,
      filename: '$safeReportId.pdf',
      subject: 'Vehicle inspection report - ${report.vehicleName}',
    );
  }

  static pw.Widget _sectionTitle(String title) => pw.Text(
    title,
    style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
  );

  static pw.Widget _pdfRow(String label, String value) => pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 4),
    child: pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.SizedBox(
          width: 155,
          child: pw.Text(
            label,
            style: const pw.TextStyle(color: PdfColors.blueGrey700),
          ),
        ),
        pw.Expanded(
          child: pw.Text(
            value,
            style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
          ),
        ),
      ],
    ),
  );
}
